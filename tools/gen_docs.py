"""Write docs/measures.md, the catalogue of every DAX measure of SM_NYC_Taxi, from semantic-model/gen_model.py."""
import importlib.util
import pathlib
from collections import OrderedDict

ROOT = pathlib.Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location("gen_model", ROOT / "semantic-model" / "gen_model.py")
gm = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gm)

ORDER = ["Core", "Fees", "Averages", "Payments", "Airports", "Time", "Shares", "Labels", "Quality", "Flows", "Profile"]


def cell(text):
    return text.replace("|", "\\|")


def main():
    folders = OrderedDict()
    for name, dax, fmt, folder, desc in gm.M:
        folders.setdefault(folder, []).append((name, dax, fmt, desc))
    keys = sorted(folders, key=lambda f: (ORDER.index(f) if f in ORDER else len(ORDER), f))
    out = ["# Measures", "",
           f"The semantic model `SM_NYC_Taxi` holds {len(gm.M)} DAX measures, all in the `Trips` table and grouped in display folders.",
           "This page is generated by `tools/gen_docs.py` from `semantic-model/gen_model.py`; do not edit it by hand.", ""]
    out.append("| Folder | Measures |")
    out.append("|--------|---------:|")
    for f in keys:
        out.append(f"| [{f}](#{f.lower()}) | {len(folders[f])} |")
    out.append("")
    for f in keys:
        out += [f"## {f}", "", "| Measure | Format | Definition |", "|---------|--------|------------|"]
        for name, dax, fmt, desc in folders[f]:
            label = f"**{cell(name)}**" + (f"<br>{cell(desc)}" if desc else "")
            out.append(f"| {label} | `{cell(fmt)}` | `{cell(dax)}` |" if fmt else f"| {label} | text | `{cell(dax)}` |")
        out.append("")
    (ROOT / "docs" / "measures.md").write_text("\n".join(out), encoding="utf-8")
    print(f"docs/measures.md: {len(gm.M)} measures in {len(keys)} folders")


if __name__ == "__main__":
    main()
