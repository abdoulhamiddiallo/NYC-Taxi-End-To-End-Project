"""Keep NB_03_Deploy_Report in step with report/gen_report.py.

The report is generated by the same code in two places: report/gen_report.py (run locally, writes the PBIR folder)
and the notebook NB_03_Deploy_Report (run in Fabric, pushes the definition through the REST API). Everything between
the palette marker and the build section is shared. This script copies that region from the script into the
notebook (default) or only checks that both are identical (--check, used by the CI).
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SCRIPT = ROOT / "report" / "gen_report.py"
NOTEBOOK = ROOT / "notebooks" / "NB_03_Deploy_Report.py"
START = "# ------------------------------------------------------------------ palette"


END = "\n# ==================================================================== build"


def region(text):
    i = text.index(START)
    j = text.index(END, i)
    return i, j


def main():
    script = SCRIPT.read_text(encoding="utf-8")
    notebook = NOTEBOOK.read_text(encoding="utf-8")
    si, sj = region(script)
    ni, nj = region(notebook)
    shared = script[si:sj]
    if notebook[ni:nj] == shared:
        print("NB_03 is in sync with report/gen_report.py")
        return 0
    if "--check" in sys.argv:
        print("NB_03 differs from report/gen_report.py: run python tools/sync_notebook.py")
        return 1
    NOTEBOOK.write_text(notebook[:ni] + shared + notebook[nj:], encoding="utf-8")
    print("NB_03 updated from report/gen_report.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())
